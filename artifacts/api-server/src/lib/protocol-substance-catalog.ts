import type {
  ProtocolSubstanceCatalogSnapshot,
  Substance,
  SubstanceBlendComponent,
} from "@workspace/db";
import { substanceDurationMinutes } from "./substance-duration";

export function buildProtocolSubstanceCatalogSnapshot(
  substance: Substance,
  components: SubstanceBlendComponent[],
): ProtocolSubstanceCatalogSnapshot {
  return {
    id: substance.id,
    name: substance.name,
    category: substance.category,
    color: substance.color,
    defaultDose: substance.defaultDose,
    unit: substance.unit,
    maxSessionsPerWeek: substance.maxSessionsPerWeek,
    intervalDays: substance.intervalDays,
    notes: substance.notes,
    pricePerUnit: substance.pricePerUnit,
    procedureType: substance.procedureType,
    viaUso: substance.viaUso,
    frequenciaBase: substance.frequenciaBase,
    doctorParticipation: substance.doctorParticipation,
    durationMinutes: substanceDurationMinutes(substance),
    description: substance.description,
    mainFunction: substance.mainFunction,
    perceivedEffects: substance.perceivedEffects,
    timeToEffect: substance.timeToEffect,
    starRating: substance.starRating,
    bodySystemEffects: substance.bodySystemEffects,
    categoryMeters: substance.categoryMeters,
    longevityBenefit: substance.longevityBenefit,
    qualityOfLifeImpact: substance.qualityOfLifeImpact,
    sleepBenefit: substance.sleepBenefit,
    energyBenefit: substance.energyBenefit,
    libidoBenefit: substance.libidoBenefit,
    physicalPerformance: substance.physicalPerformance,
    muscleStrength: substance.muscleStrength,
    mentalClarity: substance.mentalClarity,
    skinHairNails: substance.skinHairNails,
    immuneSupport: substance.immuneSupport,
    contraindications: substance.contraindications,
    scientificEvidence: substance.scientificEvidence,
    categoryType: substance.categoryType,
    codigoPadcom: substance.codigoPadcom,
    subCategoria: substance.subCategoria,
    disponivel: substance.disponivel,
    tags: Array.isArray(substance.tags) ? substance.tags as string[] : null,
    blocoId: substance.blocoId,
    grau: substance.grau,
    composicao: substance.composicao,
    posologia: substance.posologia,
    areaSemantica: substance.areaSemantica,
    exigeValidacaoHumana: substance.exigeValidacaoHumana,
    unidadeId: substance.unidadeId,
    posologiaEstruturada: substance.posologiaEstruturada,
    concentrationMg: substance.concentrationMg,
    volumeAmpola: substance.volumeAmpola,
    isBlend: substance.isBlend,
    presentationQuantity: substance.presentationQuantity,
    presentationUnit: substance.presentationUnit,
    ampouleVolumeMl: substance.ampouleVolumeMl,
    components: [...components]
      .sort((a, b) => a.sortOrder - b.sortOrder || a.id - b.id)
      .map(component => ({
        id: component.id,
        substanceId: component.substanceId,
        componentSubstanceId: component.componentSubstanceId,
        sortOrder: component.sortOrder,
        componentName: component.componentName,
        doseValue: component.doseValue,
        doseUnit: component.doseUnit,
        quantity: component.quantity,
        quantityUnit: component.quantityUnit,
        notes: component.notes,
      })),
  };
}
